def load_catalog(path: str) -> dict:
    """App id (string) -> {name, anticheats}. An unreadable file gives the
    extras alone: the folder check still runs, so the lock fails closed for
    any game that ships anti-cheat files."""
    if path in _CATALOG_CACHE:
        return _CATALOG_CACHE[path]
    games: dict = {}
    try:
        with open(path, encoding="utf-8") as f:
            games = dict((json.load(f) or {}).get("games") or {})
    except (OSError, ValueError, AttributeError):
        games = {}
    for k, v in EXTRA_GAMES.items():
        games.setdefault(k, v)
    _CATALOG_CACHE[path] = games
    return games


def scan_folder(game_dir: str, listdir=os.listdir, isdir=os.path.isdir, max_dirs: int = 64) -> dict:
    """The first anti-cheat marker in the game folder or one level below,
    as {marker, product, folder}, or {}. Reads names only - never opens a
    file. Bounded so a game with thousands of folders costs a fixed walk."""
    if not game_dir:
        return {}
    try:
        entries = listdir(game_dir)
    except OSError:
        return {}
    for name in entries:
        product = FOLDER_MARKERS.get(name.lower())
        if product:
            return {"marker": name, "product": product, "folder": game_dir}
    looked = 0
    for name in sorted(entries):
        if looked >= max_dirs:
            break
        sub = os.path.join(game_dir, name)
        if not isdir(sub):
            continue
        looked += 1
        try:
            inner = listdir(sub)
        except OSError:
            continue
        for child in inner:
            product = FOLDER_MARKERS.get(child.lower())
            if product:
                return {"marker": child, "product": product, "folder": sub}
    return {}


def verdict(app_id: int, catalog: dict, folder_hit: dict, overrides: dict) -> dict:
    """Whether mods are locked for this game, and why.

    locked: installs and enables are refused (frontend and backend).
    detected: an anti-cheat was found at all (an override keeps it true).
    override_allowed / override_on: the per-game escape hatch.
    """
    app_id = int(app_id or 0)
    listed = catalog.get(str(app_id)) if app_id else None
    products: list = list((listed or {}).get("anticheats") or [])
    source = "list" if listed else ""
    if folder_hit:
        if folder_hit.get("product") and folder_hit["product"] not in products:
            products.append(folder_hit["product"])
        source = source or "folder"
    detected = bool(products)
    allowed = detected and app_id not in NO_OVERRIDE
    on = bool(allowed and overrides.get(str(app_id)))
    return {
        "detected": detected,
        "locked": detected and not on,
        "products": products,
        "source": source,
        "marker": (folder_hit or {}).get("marker", ""),
        "name": (listed or {}).get("name", ""),
        "override_allowed": allowed,
        "override_on": on,
        "offline_note": OFFLINE_NOTES.get(app_id, ""),
    }


def lock_message(v: dict) -> str:
    """The refusal every gated backend call returns."""
    what = ", ".join(v.get("products") or []) or "an anti-cheat"
    return (f"Mods are locked for this game: it uses {what}, and a modded game can get the "
            "account banned. Nothing was installed or switched on.")


# ---- Way back after a crash --------------------------------------------------

# A run shorter than this is treated as a failed start: the game closed
# before anyone could have played. Long enough to get past a splash screen
# and a crash on load, short enough that a real session never trips it.
QUICK_EXIT_SECONDS = 60
# Two failed starts in a row after a mod change, then the offer. One can be
# a fluke (a driver hiccup, the user backing out of a launcher).
FAILS_TO_OFFER = 2
# Undo stays available this long after a restore.
UNDO_SECONDS = 7 * 24 * 3600


def active(mod_set: dict) -> list:
    """The switched-on mods of a {folder: enabled} set, sorted: what a run
    actually loaded, and so what "changed" is measured on."""
    return sorted(str(k) for k, on in (mod_set or {}).items() if on)


def clean_set(mods) -> dict:
    """{folder: bool} from whatever the frontend sent, bounded."""
    out = {}
    if isinstance(mods, dict):
        for k, v in list(mods.items())[:5000]:
            if isinstance(k, str) and k and len(k) < 512:
                out[k] = bool(v)
    return out


def on_launch(state: dict, mods: dict, now: float) -> dict:
    """A game started with this mod set. Kept as the open session; the
    failure streak resets when the set differs from the one that failed."""
    st = dict(state or {})
    mods = clean_set(mods)
    sess = st.get("session")
    # Steam can announce one start twice (launcher handing over): keep the
    # first start time, or every launcher would look like a quick exit.
    if sess and now - float(sess.get("started") or 0) < 15 and active(sess.get("set")) == active(mods):
        return st
    if st.get("fail_set") is not None and active(st.get("fail_set")) != active(mods):
        st["fails"] = 0
        st["fail_set"] = None
    st["session"] = {"set": mods, "started": float(now)}
    return st


def changed_since_good(st: dict, mods: dict) -> bool:
    lkg = st.get("lkg")
    if not lkg:
        # Never seen a clean run: any mod switched on is unproven.
        return bool(active(mods))
    return active(lkg.get("set")) != active(mods)


def on_exit(state: dict, now: float, crashed: bool = False) -> tuple:
    """The game stopped. Returns (state, event): event is "clean",
    "failed", "offer" (this exit made the restore offer) or "" (no session
    was open, e.g. the plugin started while the game ran)."""
    st = dict(state or {})
    sess = st.pop("session", None)
    if not sess:
        return st, ""
    started = sess.get("started")
    ran = max(0.0, float(now) - float(now if started is None else started))
    mods = sess.get("set") or {}
    st["last_run"] = {"seconds": int(ran), "crashed": bool(crashed), "at": int(now)}
    if ran >= QUICK_EXIT_SECONDS and not crashed:
        st["lkg"] = {"set": mods, "at": int(now)}
        st["fails"] = 0
        st["fail_set"] = None
        st["offer"] = False
        st["notified"] = False
        return st, "clean"
    if not changed_since_good(st, mods):
        # Same mods as the last good run: whatever went wrong, going back
        # to them changes nothing.
        return st, "failed"
    st["fails"] = int(st.get("fails") or 0) + 1
    st["fail_set"] = mods
    if st["fails"] >= FAILS_TO_OFFER and not st.get("offer"):
        st["offer"] = True
        st["notified"] = False
        return st, "offer"
    return st, "failed"


def restore_plan(state: dict, current: dict) -> dict:
    """What "Restore last working mods" would switch. Mods installed since
    the good run go off; mods that were on then come back on. Nothing is
    ever uninstalled, and a mod removed since is reported, not reinstalled.
    Without a clean run on record the target is every mod off."""
    current = clean_set(current)
    lkg = (state or {}).get("lkg")
    target = (lkg or {}).get("set") or {}
    changes = []
    for folder, on in sorted(current.items()):
        want = bool(target.get(folder, False))
        if want != on:
            changes.append({"folder": folder, "enabled": want})
    missing = sorted(f for f, on in target.items() if on and f not in current)
    return {
        "changes": changes,
        "missing": missing,
        "lkg_at": int((lkg or {}).get("at") or 0),
        "vanilla": not lkg,
    }


def after_restore(state: dict, previous: dict, now: float) -> dict:
    st = dict(state or {})
    st["offer"] = False
    st["notified"] = True
    st["fails"] = 0
    st["fail_set"] = None
    st["undo"] = {"set": clean_set(previous), "at": int(now)}
    return st


def undo_plan(state: dict, current: dict, now: float) -> dict:
    """Switch back to the set that was live before the restore."""
    undo = (state or {}).get("undo")
    if not undo or now - float(undo.get("at") or 0) > UNDO_SECONDS:
        return {"changes": [], "available": False}
    current = clean_set(current)
    target = undo.get("set") or {}
    changes = [{"folder": f, "enabled": bool(target[f])}
               for f, on in sorted(current.items()) if f in target and bool(target[f]) != on]
    return {"changes": changes, "available": True}


def summary(state: dict, now: float) -> dict:
    st = state or {}
    undo = st.get("undo")
    return {
        "offer": bool(st.get("offer")),
        "fails": int(st.get("fails") or 0),
        "lkg_at": int((st.get("lkg") or {}).get("at") or 0),
        "undo": bool(undo and now - float(undo.get("at") or 0) <= UNDO_SECONDS),
        "last_run": st.get("last_run") or None,
    }


def wer_crashed(exe_names, since: float, until: float, roots, listdir=os.listdir,
                getmtime=os.path.getmtime) -> str:
    """A Windows Error Reporting crash report for one of these executables,
    written while the game ran: the folder name, or "". WER names each
    report AppCrash_<exe>_<hash>_<hash>_<id>; only names and timestamps are
    read. Steam itself tells plugins nothing about how a game exited."""
    wanted = set()
    for n in exe_names or []:
        n = os.path.basename(str(n or "")).strip().lower()
        if n.endswith(".exe"):
            n = n[:-4]
        if n:
            wanted.add(n)
    if not wanted:
        return ""
    for root in roots or []:
        try:
            names = listdir(root)
        except OSError:
            continue
        for name in names:
            low = name.lower()
            if not low.startswith("appcrash_"):
                continue
            exe = low[len("appcrash_"):].split(".exe_", 1)[0]
            # WER truncates long exe names; a prefix match covers that.
            if not any(exe == w or (len(exe) >= 16 and w.startswith(exe)) for w in wanted):
                continue
            try:
                t = getmtime(os.path.join(root, name))
            except OSError:
                continue
            if since - 5 <= t <= until + 30:
                return name
    return ""


# ---- Update counts (game page badge, tile dots) ---------------------------------

UPDATE_TTL_SECONDS = 6 * 3600
# At most this many games refreshed from Nexus per call, and calls that do
# reach Nexus at least this far apart. Every game's list is one GraphQL
# request per 20 mods; the check_updates the Updates page runs refreshes the
# same cache for free.
REFRESH_PER_CALL = 3
REFRESH_SPACING_SECONDS = 20


def stale_domains(cache: dict, domains, now: float, has_mods) -> list:
    """Domains whose cached Nexus versions are missing or older than the
    TTL, oldest first, limited to games that have tracked mods."""
    out = []
    for d in domains or []:
        if not has_mods(d):
            continue
        at = float(((cache or {}).get(d) or {}).get("at") or 0)
        if now - at >= UPDATE_TTL_SECONDS:
            out.append((at, d))
    return [d for _at, d in sorted(out)]


def updates_from_versions(records: dict, versions: dict, norm, is_newer) -> list:
    """Folders with an update, from install records and cached Nexus
    versions ({mod_id: version}). Mirrors check_updates: companions follow
    their parent, collection pins are respected, an ignored version stays
    ignored."""
    out = []
    for folder, rec in (records or {}).items():
        if not isinstance(rec, dict) or not rec.get("mod_id") or rec.get("source") == "companion":
            continue
        if rec.get("source") == "collection":
            continue
        cur = versions.get(str(rec["mod_id"]))
        if cur is None:
            continue
        cur = norm(cur)
        if rec.get("ignore_update") and norm(rec["ignore_update"]) == cur:
            continue
        if is_newer(cur, norm(rec.get("page_version") or rec.get("version"))):
            out.append(folder)
    return sorted(out)
