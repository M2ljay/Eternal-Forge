"""Forge: the anti-cheat lock, the way back after a crash, and the mod
update counts behind the game page's Mods section and the tile dots.

Pure logic only - no Decky, no network, no settings file. main.py owns the
state file, the Plugin methods and the wrappers that refuse installs.

Anti-cheat sources, in the order they are asked:

1. A per-game override the user turned on, with a confirmation, for a game
   that allows one. Nothing else unlocks a game.
2. py_modules/anticheat_games.json: Steam app ids with a client-side
   anti-cheat, generated by tools/make_anticheat_list.py from
   AreWeAntiCheatYet's games.json (MIT). Plus EXTRA_GAMES below.
3. Anti-cheat files in the game's own folder: the marker list Core's
   Gaming Mode agent uses for its anti-cheat safe mode
   (eternal-core Source/GamingModeAgent/GamingMode.Services/
   AntiCheatProtection.cs, AntiCheatCatalog.FolderMarkers), so a game the
   list has never heard of is still caught.

Steam's store pages carry a kernel anti-cheat disclosure since October
2024, but the client exposes no documented field for it to plugins, so it
is not read.
"""

